/**
 * Build and run `examples/go-consumer` against a local checkout of the Go fleet.
 *
 * The fleet is published (`v0.3.0` on `proxy.golang.org`, at these same import paths —
 * `go get github.com/cdktn-io/cdktn-aws-go/s3@v0.3.0`), but this example is deliberately *not*
 * built the way a consumer would build it: it exists to measure and prove the fleet as it stands
 * in a local checkout, not the last release. So it is built
 * in **workspace mode**: this script
 * writes a `go.work` naming the local module directories, which is why
 * `examples/go-consumer/go.work` is generated and gitignored rather than committed — a committed
 * one would bake this machine's checkout layout into the repository.
 *
 * The fleet root defaults to `../cdktn-aws-go`, the same `CDKTN_AWS_GO_ROOT` convention
 * `scripts/check-go-size.mjs` and the manifest tests use.
 *
 *   node scripts/go-consumer.mjs                  # write go.work, go build, go run
 *   node scripts/go-consumer.mjs --work-only      # write go.work and stop
 *   node scripts/go-consumer.mjs --runs 3         # run the binary N times (cold vs warm kernel)
 *   node scripts/go-consumer.mjs --root /path/to/cdktn-aws-go
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const exampleDir = path.join(repoRoot, "examples", "go-consumer");

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const value = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
};

const goRoot = path.resolve(
  value("--root", process.env.CDKTN_AWS_GO_ROOT ?? path.join(repoRoot, "..", "cdktn-aws-go")),
);
const runs = Number(value("--runs", "1"));

if (!existsSync(goRoot)) {
  console.error(
    `go-consumer: no fleet checkout at ${goRoot} — clone cdktn-io/cdktn-aws-go beside this repo, ` +
      "or pass --root / set CDKTN_AWS_GO_ROOT.",
  );
  process.exit(1);
}

// The modules the example imports, read out of its own go.mod rather than duplicated here: the
// import list and the workspace can then never drift apart.
const goMod = readFileSync(path.join(exampleDir, "go.mod"), "utf-8");
const modules = [...goMod.matchAll(/^\s*github\.com\/cdktn-io\/cdktn-aws-go\/(\w+) /gm)].map(
  (m) => m[1],
);
if (modules.length === 0) {
  console.error("go-consumer: examples/go-consumer/go.mod requires no fleet modules — nothing to do.");
  process.exit(1);
}

const absent = modules.filter((m) => !existsSync(path.join(goRoot, m, "go.mod")));
if (absent.length > 0) {
  console.error(
    `go-consumer: ${absent.length} module(s) missing from ${goRoot}: ${absent.join(", ")}\n` +
      "  build and pack with `node scripts/build-fleet.mjs`, then copy each\n" +
      "  generated/<group>/dist/go/<packageName>/ into the fleet root — the exact copy commands are\n" +
      "  printed by `node scripts/release.mjs --from <ref>`.",
  );
  process.exit(1);
}

// `use` paths are written relative to the example directory so the file is at least readable;
// it is still machine-specific, and still gitignored.
const rel = (p) => {
  const r = path.relative(exampleDir, p);
  return r.startsWith(".") ? r : `./${r}`;
};
const workPath = path.join(exampleDir, "go.work");
writeFileSync(
  workPath,
  [
    "// GENERATED by scripts/go-consumer.mjs — do not commit, do not edit.",
    "// This workspace points the example at a local checkout of the fleet, so that it measures",
    "// that checkout rather than the published release.",
    "",
    "go 1.25.0",
    "",
    "use .",
    "",
    // `use`-ing the fleet directories is the wrong tool here and Go says so: a workspace module
    // may not also be replaced, and without a replacement the placeholder `v0.0.0` in the
    // example's go.mod would be resolved against the proxy — i.e. against the published release
    // rather than the checkout under test. So the fleet is brought in by `replace` alone. A
    // consumer outside this repository requires the published versions and writes none of this.
    ...modules.map(
      (m) => `replace github.com/cdktn-io/cdktn-aws-go/${m} => ${rel(path.join(goRoot, m))}`,
    ),
    "",
  ].join("\n"),
);
console.log(`go-consumer: wrote ${workPath} — ${modules.length} fleet modules from ${goRoot}`);
if (flag("--work-only")) process.exit(0);

const go = (args, opts = {}) =>
  execFileSync("go", args, { cwd: exampleDir, stdio: "inherit", ...opts });

// `go build` does not care about formatting, so a rename that widens a struct field leaves the
// example unformatted and every gate still green — which is exactly how 0.3.0's `tfType` ->
// `awsType` broke the alignment column. gofmt is syntactic and needs no fleet, so it runs first.
const unformatted = execFileSync("gofmt", ["-l", "."], {
  cwd: exampleDir,
  encoding: "utf-8",
}).trim();
if (unformatted !== "") {
  console.error(`go-consumer: not gofmt-clean — run \`gofmt -w\` on:\n${unformatted}`);
  process.exit(1);
}

console.log("go-consumer: go build ./...");
go(["build", "./..."]);
for (let i = 0; i < runs; i++) {
  console.log(`go-consumer: go run . (${i + 1}/${runs})`);
  go(["run", "."]);
}
