/**
 * M2 stage 2, deliverable 1: assemble the ONE published jsii assembly, `@cdktn/aws`.
 *
 * Shape decision — a **copy-in build step**, not a barrel over the per-group packages:
 *
 *   a jsii assembly owns every type it declares. `export * as lambda from '@cdktn/aws-lambda'`
 *   would make each group a *dependency* assembly, i.e. 258 separately published artifacts with
 *   258 `.jsii` files and cross-assembly type references — the exact opposite of "one library".
 *   So `monolith/src/<group>/` is a copy of `generated/<group>/src/`, and `monolith/src/index.ts`
 *   is `export * as <group> from './<group>'` — jsii's submodule form. One compile, one assembly,
 *   258 submodules.
 *
 * The copy is free of merge risk because the per-group sources import nothing but `cdktn` and
 * `constructs` (scripts/check-no-cross-group-imports.mjs is the gate), so moving a group one
 * directory deeper cannot change a single specifier.
 *
 * `monolith/` is entirely generated and entirely gitignored.
 *
 * Usage:
 *   node scripts/build-monolith.mjs                 # assemble + jsii compile
 *   node scripts/build-monolith.mjs --assemble-only # just write monolith/
 *   node scripts/build-monolith.mjs --pacmak python # ...and pack a target after compiling
 */
import { readdirSync, existsSync, mkdirSync, rmSync, cpSync, writeFileSync, symlinkSync, statSync } from "node:fs";
import { spawnSync } from "node:child_process";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedDir = path.join(repoRoot, "generated");
const monolithDir = path.join(repoRoot, "monolith");
const bin = (name) => path.join(repoRoot, "node_modules", ".bin", name);

const args = process.argv.slice(2);
const assembleOnly = args.includes("--assemble-only");
const pacmakIdx = args.indexOf("--pacmak");
const pacmakTargets = pacmakIdx >= 0 ? args[pacmakIdx + 1].split(",") : [];
/** jsii holds the whole 2.18M-line program in memory; the default 4 GB ceiling is not enough. */
const heapMb = Number(process.env.CDKTN_AWS_HEAP_MB ?? 16384);

const PROVIDER_VERSION = "6.62.0";
const VERSION = "0.0.0";

const groups = readdirSync(generatedDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

// ---------------------------------------------------------------- assemble

rmSync(monolithDir, { recursive: true, force: true });
mkdirSync(path.join(monolithDir, "src"), { recursive: true });

let copiedBytes = 0;
let copiedFiles = 0;
const walk = (dir) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else {
      copiedFiles++;
      copiedBytes += statSync(p).size;
    }
  }
};
for (const group of groups) {
  const src = path.join(generatedDir, group, "src");
  cpSync(src, path.join(monolithDir, "src", group), { recursive: true });
  walk(src);
}

writeFileSync(
  path.join(monolithDir, "src", "index.ts"),
  [
    "// Copyright (c) cdktn-io",
    "// SPDX-License-Identifier: MPL-2.0",
    "// Generated by scripts/build-monolith.mjs. Do not edit.",
    ...groups.map((g) => `export * as ${g} from './${g}';`),
    "",
  ].join("\n"),
);

writeFileSync(
  path.join(monolithDir, "package.json"),
  JSON.stringify(
    {
      name: "@cdktn/aws",
      version: VERSION,
      description: `cdk-terrain bindings for terraform-provider-aws ${PROVIDER_VERSION}, in ${groups.length} service submodules`,
      license: "MPL-2.0",
      private: true,
      author: { name: "cdktn-io", organization: true },
      repository: { type: "git", url: "https://github.com/cdktn-io/cdktn-aws.git" },
      stability: "experimental",
      main: "lib/index.js",
      types: "lib/index.d.ts",
      jsii: {
        outdir: "dist",
        versionFormat: "short",
        tsc: { outDir: "lib", rootDir: "src" },
        targets: {
          // Target naming follows @cdktn/provider-aws's own conventions verbatim, so the two are
          // directly comparable on every registry (its distName is "cdktn-provider-aws", module
          // "cdktn_provider_aws", java "io.cdktn.providers.aws").
          python: { distName: "cdktn-aws", module: "cdktn_aws" },
          java: {
            package: "io.cdktn.aws",
            maven: { groupId: "io.cdktn", artifactId: "cdktn-aws" },
          },
          dotnet: { namespace: "Io.Cdktn.Aws", packageId: "Io.Cdktn.Aws" },
          go: { moduleName: "github.com/cdktn-io/cdktn-aws-go", packageName: "aws" },
        },
      },
      peerDependencies: { cdktn: "^0.24.0", constructs: "^10.7.0" },
      devDependencies: { cdktn: "0.24.0", constructs: "10.7.0" },
    },
    null,
    2,
  ) + "\n",
);

writeFileSync(
  path.join(monolithDir, "README.md"),
  `# @cdktn/aws

cdk-terrain bindings for \`terraform-provider-aws\` ${PROVIDER_VERSION}, as **one jsii assembly**
with ${groups.length} service submodules.

\`\`\`ts
import { lambda, s3 } from '@cdktn/aws';

new lambda.AwsLambdaFunction(this, 'fn', { functionName: 'f', role: r.arn });
\`\`\`

Assembled by \`scripts/build-monolith.mjs\` from the committed \`generated/<group>/src\` trees.
Do not edit by hand.
`,
);

// jsii's own generated tsconfig, mirrored — same rule as the per-group packages
// (tools/aws2cdk/src/manifest.ts#tsconfigFor), so `--validate-tsconfig generated` accepts it.
writeFileSync(
  path.join(monolithDir, "tsconfig.json"),
  JSON.stringify(
    {
      compilerOptions: {
        outDir: "lib",
        rootDir: "src",
        declarationMap: false,
        inlineSourceMap: true,
        inlineSources: true,
        alwaysStrict: true,
        declaration: true,
        incremental: true,
        tsBuildInfoFile: "lib/tsconfig.tsbuildinfo",
        lib: ["es2020"],
        module: "commonjs",
        noEmitOnError: true,
        noFallthroughCasesInSwitch: true,
        noImplicitAny: true,
        noImplicitReturns: true,
        noImplicitThis: true,
        noUnusedLocals: true,
        noUnusedParameters: true,
        resolveJsonModule: true,
        skipLibCheck: true,
        strict: true,
        strictNullChecks: true,
        strictPropertyInitialization: true,
        stripInternal: false,
        target: "es2020",
        composite: false,
      },
      include: ["src/**/*.ts"],
      exclude: ["node_modules"],
    },
    null,
    2,
  ) + "\n",
);

// monolith/ is a build artifact, not a pnpm workspace member: link the two peers by hand, exactly
// the way pnpm linked them into every generated/<group>/node_modules.
mkdirSync(path.join(monolithDir, "node_modules"), { recursive: true });
for (const dep of ["cdktn", "constructs"]) {
  const real = path.join(repoRoot, "generated", "provider", "node_modules", dep);
  if (!existsSync(real)) throw new Error(`missing ${dep} in generated/provider/node_modules — run pnpm install`);
  symlinkSync(path.relative(path.join(monolithDir, "node_modules"), real), path.join(monolithDir, "node_modules", dep));
}

console.log(
  `assembled monolith/: ${groups.length} submodules, ${copiedFiles} source files, ${copiedBytes} B`,
);
if (assembleOnly) process.exit(0);

// ---------------------------------------------------------------- compile

const run = (label, cmd, cmdArgs) => {
  const t0 = Date.now();
  const r = spawnSync(cmd, cmdArgs, {
    cwd: monolithDir,
    encoding: "utf8",
    env: { ...process.env, NODE_OPTIONS: `${process.env.NODE_OPTIONS ?? ""} --max-old-space-size=${heapMb}`.trim() },
    maxBuffer: 256 * 1024 * 1024,
  });
  const secs = ((Date.now() - t0) / 1000).toFixed(1);
  const output = `${r.stdout ?? ""}${r.stderr ?? ""}`;
  const codes = {};
  for (const m of output.matchAll(/JSII(\d+)/g)) codes[`JSII${m[1]}`] = (codes[`JSII${m[1]}`] ?? 0) + 1;
  const summary = Object.entries(codes)
    .sort()
    .map(([k, v]) => `${k}x${v}`)
    .join(" ");
  if (r.status !== 0) {
    console.error(`${label}: FAIL (exit ${r.status}) after ${secs}s ${summary}`);
    console.error(output.slice(-20000));
    process.exit(1);
  }
  console.log(`${label}: OK in ${secs}s${summary ? ` — ${summary}` : " — no JSII diagnostics"}`);
  return { secs, codes, output };
};

run(`jsii (heap ${heapMb} MB)`, bin("jsii"), ["--tsconfig", "tsconfig.json", "--validate-tsconfig", "generated"]);

// ---------------------------------------------------------------- lazify

/**
 * TypeScript compiles `export * as lambda from './lambda'` to `exports.lambda = require("./lambda")`
 * — 258 eager `require`s, so importing the package to use one service parses all 2,660 modules.
 * @cdktn/provider-aws has the same shape (2,405 eager `require`s in its `lib/index.js`), which is
 * why the eager top-level import is a near-wash between the two.
 *
 * This pass replaces the barrel's body with one self-replacing getter per submodule. It is a
 * post-compile rewrite of the EMITTED `lib/index.js` only: `lib/index.d.ts` and the `.jsii`
 * assembly are untouched, so the type surface and every non-JS target still see exactly what jsii
 * compiled. It runs BEFORE pacmak so the tarball the jsii kernel loads for Python/Java/.NET carries
 * the lazy barrel too — the kernel reaches a submodule by property access, which a getter serves.
 */
if (!args.includes("--no-lazify")) {
  const indexJs = path.join(monolithDir, "lib", "index.js");
  const before = statSync(indexJs).size;
  writeFileSync(
    indexJs,
    `"use strict";
// Lazified by scripts/build-monolith.mjs (post-compile). See that file for why.
Object.defineProperty(exports, "__esModule", { value: true });
const SUBMODULES = ${JSON.stringify(groups)};
for (const name of SUBMODULES) {
  Object.defineProperty(exports, name, {
    enumerable: true,
    configurable: true,
    get() {
      const mod = require("./" + name);
      Object.defineProperty(exports, name, { value: mod, enumerable: true, configurable: true });
      return mod;
    },
  });
}
`,
  );
  // A getter that throws would be invisible until a consumer touched it, so prove every one of
  // the 258 resolves, in this process, right now.
  const probe = spawnSync(
    process.execPath,
    ["--max-old-space-size=8192", "-e", `const m=require(${JSON.stringify(indexJs)});let n=0;for(const k of Object.keys(m)){if(!m[k])throw new Error('empty submodule '+k);n++}console.log(n)`],
    { encoding: "utf8" },
  );
  if (probe.status !== 0 || probe.stdout.trim() !== String(groups.length)) {
    console.error(`lazify: FAIL — ${probe.stdout}${probe.stderr}`);
    process.exit(1);
  }
  console.log(`lazify: OK — lib/index.js ${before} B -> ${statSync(indexJs).size} B, all ${groups.length} getters resolve`);
}

for (const target of pacmakTargets) {
  run(`jsii-pacmak --targets ${target}`, bin("jsii-pacmak"), ["--targets", target]);
}
